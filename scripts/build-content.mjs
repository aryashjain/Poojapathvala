// Reads content/<topic>/topic.md and content/<topic>/<doc>.md and writes
// src/content.generated.js, so the Worker can ship the library as plain data.
import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { parseFrontmatter } from '../src/markdown.js';

const ROOT = path.resolve(import.meta.dirname, '..');
const CONTENT_DIR = path.join(ROOT, 'content');
const OUTPUT = path.join(ROOT, 'src', 'content.generated.js');
const SLUG = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;

function fail(message) {
  throw new Error('[build-content] ' + message);
}

function checkSlug(slug, where) {
  if (!SLUG.test(slug)) fail('"' + where + '" must be a lowercase-hyphen slug (got "' + slug + '").');
}

function checkDate(date, where) {
  if (date && !/^\d{4}-\d{2}-\d{2}$/.test(date)) fail(where + ' has date "' + date + '"; use YYYY-MM-DD.');
}

function byOrderThenTitle(a, b) {
  return a.order - b.order || a.title.localeCompare(b.title);
}

async function readMarkdown(file) {
  return parseFrontmatter(await readFile(file, 'utf8'));
}

async function main() {
  const entries = await readdir(CONTENT_DIR, { withFileTypes: true });
  const topicDirs = entries.filter((entry) => entry.isDirectory() && !entry.name.startsWith('.'));
  const topics = [];

  for (const dir of topicDirs) {
    checkSlug(dir.name, 'content/' + dir.name);
    const topicDir = path.join(CONTENT_DIR, dir.name);

    let topicFile;
    try {
      topicFile = await readMarkdown(path.join(topicDir, 'topic.md'));
    } catch {
      fail('content/' + dir.name + '/topic.md is missing.');
    }
    const meta = topicFile.data;
    checkDate(meta.date, 'content/' + dir.name + '/topic.md');

    const files = (await readdir(topicDir, { withFileTypes: true }))
      .filter((file) => file.isFile() && file.name.endsWith('.md') && file.name !== 'topic.md' && !file.name.startsWith('.'));

    const docs = [];
    for (const file of files) {
      const slug = file.name.slice(0, -3);
      const where = 'content/' + dir.name + '/' + file.name;
      checkSlug(slug, where);
      const { data, body } = await readMarkdown(path.join(topicDir, file.name));
      const date = data.date || data.updatedAt || '';
      checkDate(date, where);
      docs.push({
        slug,
        title: data.title || slug,
        hindiTitle: data.hindiTitle || '',
        description: data.description || '',
        descriptionHi: data.descriptionHi || '',
        order: Number(data.order) || 9999,
        date,
        author: data.author || '',
        readingTime: data.readingTime || '',
        tags: Array.isArray(data.tags) ? data.tags : [],
        featured: data.featured === 'true' || data.featured === true,
        body: body.trim(),
      });
    }

    docs.sort(byOrderThenTitle);
    topics.push({
      slug: dir.name,
      title: meta.title || dir.name,
      titleHi: meta.titleHi || '',
      description: meta.description || '',
      descriptionHi: meta.descriptionHi || '',
      order: Number(meta.order) || 9999,
      intro: topicFile.body.trim(),
      docs,
    });
  }

  topics.sort(byOrderThenTitle);

  const source =
    '// AUTO-GENERATED by scripts/build-content.mjs. Edit files in content/ instead.\n' +
    'export const TOPICS = ' + JSON.stringify(topics, null, 2) + ';\n';
  await writeFile(OUTPUT, source);

  const docCount = topics.reduce((sum, topic) => sum + topic.docs.length, 0);
  console.log('[build-content] wrote ' + topics.length + ' topics, ' + docCount + ' texts to src/content.generated.js');
}

main().catch((error) => {
  console.error(error.message);
  process.exit(1);
});
